"""Render Painting TV's logo, launcher icon and TV banner.

The logo is a P built from rounded screen pixels, shrinking like halftone; it is drawn in white
over Van Gogh's Wheat Field with Cypresses (1889, The Met, public domain), bundled with the app.
Run with: uv run --locked --extra images python -m tools.app_icons
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
SOURCE = ROOT / "app/src/main/assets/images/met-436535.jpg"
# Inter Display ExtraBold, SIL Open Font License (tools/fonts/OFL.txt).
FONT = ROOT / "tools/fonts/InterDisplay-ExtraBold.ttf"
# Sky, cypresses and wheat. The icon's crop leaves room for the launcher mask around them.
ICON_CROP = (1660, 595, 3734, 2669)
BANNER_CROP = (160, 760, 3700, 2751)
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
SUPERSAMPLE = 4
PIXELS = ["###.", "#..#", "#..#", "###.", "#...", "#..."]

type Cell = tuple[float, float, float]


def cells() -> list[Cell]:
    """The logo's pixels as (centre x, centre y, side) on a 4 x 6 grid of unit cells."""
    return [(i + 0.5, j + 0.5, 0.94 - 0.03 * (i + j))
            for j, row in enumerate(PIXELS) for i, pixel in enumerate(row) if pixel == "#"]


def path_data(unit: float, left: float, top: float) -> str:
    """The logo as vector path data: rounded squares [unit] wide per cell, from ([left], [top])."""
    parts = []
    for x, y, side in cells():
        size, radius = side * unit, side * unit * 0.3
        x0, y0 = left + x * unit - size / 2, top + y * unit - size / 2
        straight = size - 2 * radius
        arc = f"a{radius:.3f},{radius:.3f} 0 0 1"
        parts.append(
            f"M{x0 + radius:.3f},{y0:.3f}h{straight:.3f}{arc} {radius:.3f},{radius:.3f}"
            f"v{straight:.3f}{arc} {-radius:.3f},{radius:.3f}h{-straight:.3f}"
            f"{arc} {-radius:.3f},{-radius:.3f}v{-straight:.3f}{arc} {radius:.3f},{-radius:.3f}z")
    return "".join(parts)


def vector(size: int, viewport: int, height: float, comment: str) -> str:
    """A white logo [height] units tall, centred in a square vector drawable."""
    unit = height / len(PIXELS)
    left, top = (viewport - unit * len(PIXELS[0])) / 2, (viewport - height) / 2
    return (f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            f"    <!-- {comment} Generated by tools/app_icons.py. -->\n"
            f'    <path android:fillColor="#FFFFFF"\n'
            f'        android:pathData="{path_data(unit, left, top)}" />\n'
            f"</vector>\n")


def draw_logo(image: Image.Image, centre_x: float, centre_y: float, height: float) -> None:
    """Draws the white logo over a soft shadow, so it reads on any part of the painting."""
    unit = height / len(PIXELS)
    left, top = centre_x - unit * len(PIXELS[0]) / 2, centre_y - height / 2

    def paint(target: Image.Image, colour: tuple[int, int, int, int], drop: float) -> None:
        draw = ImageDraw.Draw(target)
        for x, y, side in cells():
            size = side * unit
            x0, y0 = left + x * unit - size / 2, top + y * unit - size / 2 + drop
            draw.rounded_rectangle((x0, y0, x0 + size, y0 + size), radius=size * 0.3, fill=colour)

    shadow = Image.new("RGBA", image.size, (0, 0, 0, 0))
    paint(shadow, (0, 0, 0, 130), height * 0.02)
    image.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(height * 0.04)))
    paint(image, (255, 255, 255, 255), 0)


def painting(crop: tuple[int, int, int, int], width: int, height: int) -> Image.Image:
    with Image.open(SOURCE) as image:
        art = image.convert("RGB").crop(crop).resize((width, height), Image.Resampling.LANCZOS)
    return ImageEnhance.Color(art).enhance(1.2).convert("RGBA")


def darken_centre(image: Image.Image, edge: int, centre: int) -> None:
    """Shades the painting, more behind the logo, without a visible vignette ring."""
    image.alpha_composite(Image.new("RGBA", image.size, (0, 0, 0, edge)))
    glow = Image.new("L", image.size, 0)
    w, h = image.size
    ImageDraw.Draw(glow).ellipse((w * 0.25, h * 0.25, w * 0.75, h * 0.75), fill=centre - edge)
    shade = Image.new("RGBA", image.size, (0, 0, 0, 255))
    shade.putalpha(glow.filter(ImageFilter.GaussianBlur(w * 0.12)))
    image.alpha_composite(shade)


def background(scale: float) -> Image.Image:
    """Adaptive icon background: 108dp of painting. The vector logo is the foreground."""
    size = round(108 * scale)
    image = painting(ICON_CROP, size, size)
    darken_centre(image, 40, 110)
    return image.convert("RGB")


def legacy(scale: float) -> Image.Image:
    """48dp icon for file managers and launchers without adaptive icons."""
    size = round(48 * scale)
    big = size * SUPERSAMPLE
    # The adaptive icon shows the middle 72dp of 108dp; show the same part of the painting.
    image = background(scale * SUPERSAMPLE * 2 / 3).convert("RGBA").crop(
        (big // 4, big // 4, big // 4 + big, big // 4 + big))
    draw_logo(image, big / 2, big / 2, big * 0.55)
    mask = Image.new("L", (big, big), 0)
    margin = round(big / 48)
    ImageDraw.Draw(mask).rounded_rectangle(
        (margin, margin, big - margin, big - margin), radius=round(big * 0.22), fill=255)
    image.putalpha(mask)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def banner(scale: float) -> Image.Image:
    """The 160dp x 90dp TV banner: the painting edge to edge, the logo and the name."""
    width, height = round(160 * scale) * SUPERSAMPLE, round(90 * scale) * SUPERSAMPLE
    image = painting(BANNER_CROP, width, height)
    # Darkens towards the left, behind the name.
    fade = Image.linear_gradient("L").rotate(90).resize((width, height)).point(lambda v: v * 4 // 5)
    shade = Image.new("RGBA", (width, height), (6, 6, 8, 255))
    shade.putalpha(fade)
    image.alpha_composite(shade)
    logo = height * 0.3
    left = width * 0.08
    draw_logo(image, left + logo / 3, height / 2, logo)
    font = ImageFont.truetype(str(FONT), round(height * 0.16))
    name_left = left + logo * 2 / 3 + width * 0.035
    shadow = Image.new("RGBA", image.size, (0, 0, 0, 0))
    ImageDraw.Draw(shadow).text((name_left, height / 2 + height * 0.008), "Painting TV", font=font,
                                fill=(0, 0, 0, 140), anchor="lm")
    image.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(height * 0.015)))
    ImageDraw.Draw(image).text((name_left, height / 2), "Painting TV", font=font, fill="white",
                               anchor="lm")
    return image.resize((width // SUPERSAMPLE, height // SUPERSAMPLE),
                        Image.Resampling.LANCZOS).convert("RGB")


def main() -> None:
    drawable = RES / "drawable"
    (drawable / "ic_launcher_foreground.xml").write_text(vector(
        108, 108, 44, "The logo, within the adaptive icon's 66dp safe zone; also its monochrome layer."))
    (drawable / "ic_notification.xml").write_text(vector(
        24, 24, 20, "Notification small icons use an opaque white silhouette on transparency."))
    for name, scale in DENSITIES.items():
        folder = RES / f"drawable-{name}"
        folder.mkdir(exist_ok=True)
        background(scale).save(folder / "ic_launcher_background.png", optimize=True)
        banner(scale).save(folder / "tv_banner.png", optimize=True)
        legacy(scale).save(RES / f"mipmap-{name}/ic_launcher.png", optimize=True)


if __name__ == "__main__":
    main()
